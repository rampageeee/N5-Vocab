#!/usr/bin/env node
/* ============================================================
   build-kana-data.js
   Generates data/kana-data.js from a LOCAL clone of KanjiVG.

   Why this runs locally instead of Claude fetching it directly:
   GitHub disallows automated fetch (robots.txt) and raw.github-
   usercontent.com isn't reachable from a chat tool call without a
   prior search hit landing on it — so pulling ~150 individual SVGs
   live in a chat session isn't possible. This script does the exact
   same extraction the ORIGINAL data/kanji-data.js was presumably
   built with, just run here instead of there.

   USAGE
     git clone https://github.com/KanjiVG/kanjivg.git
     node tools/build-kana-data.js ./kanjivg/kanji ./data/kana-data.js

   Each KanjiVG file is named by the lowercase, 5-digit zero-padded
   hex Unicode codepoint of the character, e.g. あ (U+3042) →
   03042.svg. Stroke paths are the <path d="..."> elements inside
   the kvg:StrokePaths_* group, in document order — which IS stroke
   order. Stroke-number labels are <text>, not <path>, so a plain
   `<path` scan naturally skips them without extra filtering.

   The character list below MUST stay in sync with the CHARS built
   in js/kana.js (GOJUON / DAKUTEN / YOON). It's duplicated here
   rather than shared at runtime because this script runs in Node,
   kana.js runs in the browser — if you add a kana to one, add it
   to the other.
   ============================================================ */
'use strict';
const fs = require('fs');
const path = require('path');

// ---- same 46 + 25 + (6 small-kana for yōon) character set as kana.js ----
// Yōon needs only the 3 small ゃゅょ (hira) + 3 small ャュョ (kata) beyond
// gojuon/dakuten — the base consonant kana (き/し/ち/etc.) are already here.
const GOJUON_HIRA = 'あいうえおかきくけこさしすせそたちつてとなにぬねのはひふへほまみむめもやゆよらりるれろわをん';
const GOJUON_KATA = 'アイウエオカキクケコサシスセソタチツテトナニヌネノハヒフヘホマミムメモヤユヨラリルレロワヲン';
const DAKUTEN_HIRA = 'がぎぐげござじずぜぞだぢづでどばびぶべぼぱぴぷぺぽ';
const DAKUTEN_KATA = 'ガギグゲゴザジズゼゾダヂヅデドバビブベボパピプペポ';
const SMALL_Y_HIRA = 'ゃゅょ';
const SMALL_Y_KATA = 'ャュョ';

const ALL_CHARS = [...new Set([
  ...GOJUON_HIRA, ...GOJUON_KATA,
  ...DAKUTEN_HIRA, ...DAKUTEN_KATA,
  ...SMALL_Y_HIRA, ...SMALL_Y_KATA
])];

function codepointHex(ch) {
  return ch.codePointAt(0).toString(16).padStart(5, '0');
}

function extractStrokes(svgText) {
  // Grab the kvg:StrokePaths_* group only, then every path d="" within it.
  const groupMatch = svgText.match(/<g[^>]*id="kvg:StrokePaths_[^"]*"[^>]*>([\s\S]*?)<\/g>\s*<g[^>]*id="kvg:StrokeNumbers/);
  const scope = groupMatch ? groupMatch[1] : svgText;   // fall back to whole file if structure differs
  const paths = [];
  const re = /<path\b[^>]*\sd="([^"]+)"/g;
  let m;
  while ((m = re.exec(scope))) paths.push(m[1]);
  return paths;
}

function main() {
  const kanjivgDir = process.argv[2];
  const outPath = process.argv[3] || path.join(__dirname, '..', 'data', 'kana-data.js');
  if (!kanjivgDir) {
    console.error('Usage: node build-kana-data.js <path-to-kanjivg/kanji> [output-path]');
    console.error('       (clone https://github.com/KanjiVG/kanjivg.git first)');
    process.exit(1);
  }

  const result = {};
  const missing = [];

  for (const ch of ALL_CHARS) {
    const hex = codepointHex(ch);
    const file = path.join(kanjivgDir, `${hex}.svg`);
    if (!fs.existsSync(file)) { missing.push(`${ch} (${hex}.svg)`); continue; }
    const svg = fs.readFileSync(file, 'utf8');
    const strokes = extractStrokes(svg);
    if (strokes.length === 0) { missing.push(`${ch} (${hex}.svg — no strokes found)`); continue; }
    result[ch] = strokes;
  }

  const body = Object.entries(result)
    .map(([ch, strokes]) => `  ${JSON.stringify(ch)}: [\n${strokes.map(d => `    ${JSON.stringify(d)}`).join(',\n')}\n  ]`)
    .join(',\n');

  const out = `/* Generated by tools/build-kana-data.js from a local KanjiVG clone. */\n`
    + `window.KANA_DATA = {\n${body}\n};\n`;

  fs.writeFileSync(outPath, out, 'utf8');

  console.log(`Wrote ${Object.keys(result).length}/${ALL_CHARS.length} glyphs to ${outPath}`);
  if (missing.length) {
    console.log(`Missing (${missing.length}):`);
    missing.forEach(m => console.log('  ' + m));
  }
}

main();
